package io.knotra;

/**
 * 单次 Activation 的生命周期状态。
 *
 * <p>激活是组件的一次事务化执行，状态推进与暂存注册的发布、回滚保持一致。
 */
public enum ActivationState {
    /** 启动事务进行中：用户 start() 代码已执行或正在执行，暂存内容尚未提交。 */
    STARTING,
    /** 验证成功：暂存注册与子挂载已原子发布，该代际成为组件的当前激活。 */
    ACTIVE,
    /** 正在停止：激活被判定为过期、组件被重配置或进入释放流程，等待清理收敛。 */
    STOPPING,
    /** 终态：启动或清理失败，失败原因保留在诊断中。 */
    FAILED,
    /** 终态：激活及其受管资源已完全释放并结算。 */
    SETTLED
}
